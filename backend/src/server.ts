import {privateAiCosts} from './middleware/privateAiCosts.js';
import {requestProtection} from './middleware/requestProtection.js';
import {startAgentTaskWorker} from "./services/agentStory.js";
import { startRenderFallback } from "./services/renderFallback.js";
import { startScriptWorker } from "./services/scriptProduction.js";
import { startMongoGenerationFallback } from "./services/generationDispatch.js";
import { WebsiteSettings } from "./models/Finance.js";
import { startProviderMonitor } from "./services/openrouterManagement.js";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { creativeRouter } from "./routes/creative.js";
import { adminRouter } from "./routes/admin.js";
import { bootstrapAdmin, adminIdentity } from "./services/adminSecurity.js";
import { platformGate } from "./services/platformControl.js";
import { PlatformControl } from "./models/Admin.js";
import { supportRouter } from "./routes/support.js";
import { feedbackRouter } from "./routes/feedback.js";
import { notificationsRouter } from "./routes/notifications.js";
import { startNotificationWorker } from "./workers/notificationWorker.js";
import { publishingRouter } from "./routes/publishing.js";
import { youtubeWatchRouter } from "./routes/youtubeWatch.js";
import cors from "cors";
import cookieParser from "cookie-parser";
import express from "express";
import helmet from "helmet";
import { createServer } from "node:http";
import { Server } from "socket.io";
import { env } from "./config/env.js";
import { connectDatabase } from "./config/db.js";
import { errorHandler } from "./middleware/errorHandler.js";
import { accountRouter } from "./routes/account.js";
import { authRouter } from "./routes/auth.js";
import { healthRouter } from "./routes/health.js";
import { walletRouter } from "./routes/wallet.js";
import { youtubeRouter } from "./routes/youtube.js";
import { youtubeChannelRouter } from "./routes/youtubeChannel.js";
import { aiRouter } from "./routes/ai.js";
import { imagesRouter } from "./routes/images.js";
import { videosRouter } from "./routes/videos.js";
import { voiceRouter } from "./routes/voice.js";
import { studioRouter } from "./routes/studio.js";
import { editorRouter } from "./routes/editor.js";
import { seedCreditConfig } from "./services/wallet.js";
import { setRealtimeServer } from "./realtime.js";

const app = express();
app.set("trust proxy", 1);
app.disable("x-powered-by");
app.use(helmet({ contentSecurityPolicy: { directives: { "script-src": ["'self'", "https://challenges.cloudflare.com", "https://www.youtube.com", "https://s.ytimg.com"], "frame-src": ["'self'", "https://challenges.cloudflare.com", "https://www.youtube.com", "https://www.youtube-nocookie.com"], "img-src": ["'self'", "data:", "blob:", "https:"], "media-src": ["'self'", "data:", "blob:", "https:"], "connect-src": ["'self'", "https:", "wss:", ...(env.SERVE_FRONTEND ? [] : ["http://localhost:*", "ws://localhost:*"])] } } }));
app.use(cors({ origin: env.CLIENT_ORIGIN, credentials: true }));
app.use(cookieParser());
app.use(express.json({ limit: "2mb" }));
app.use("/api", requestProtection, privateAiCosts, platformGate);
app.get("/api/platform-status", async (req, res) => { const c = await PlatformControl.findById("platform"); const admin = await adminIdentity(req); const website = await WebsiteSettings.findById("public").select("siteName description supportEmail -_id").lean(); res.json({ website, maintenance: !!c?.maintenance && !admin, message: c?.message || "We will be back shortly." }); });
app.use("/api/admin", adminRouter);
app.use("/api/health", healthRouter);
app.use("/api/auth", authRouter);
app.use("/api/account", accountRouter);
app.use("/api/support", supportRouter);
app.use("/api/feedback", feedbackRouter);
app.use("/api/notifications", notificationsRouter);
app.use("/api/wallet", walletRouter);
app.use("/api/youtube", youtubeRouter);
app.use("/api/youtube", youtubeWatchRouter);
app.use("/api/youtube", youtubeChannelRouter);
app.use("/api/ai", aiRouter);
app.use("/api/publishing", publishingRouter);
app.use("/api/images", imagesRouter);
app.use("/api/videos", videosRouter);
app.use("/api/voice", voiceRouter);
app.use("/api/studio", studioRouter);
app.use("/api/editor", editorRouter);
app.use("/api/creative", creativeRouter);
app.use("/api", (_req, res) => res.status(404).json({ error: "API endpoint not found" }));
if (env.SERVE_FRONTEND) {
  const frontend = fileURLToPath(new URL("../../frontend/dist/", import.meta.url));
  app.use(express.static(frontend));
  app.get("*", (_req, res) => res.sendFile(path.join(frontend, "index.html")));
}
app.use(errorHandler);

const httpServer = createServer(app);
const io = new Server(httpServer, { transports: ["websocket"], cors: { origin: env.CLIENT_ORIGIN, credentials: true } });
setRealtimeServer(io);

await connectDatabase();
await bootstrapAdmin();
await seedCreditConfig().catch((error) => console.warn("Credit config seeding skipped:", error.message));
startNotificationWorker();
startProviderMonitor();
startMongoGenerationFallback();
startScriptWorker();
startAgentTaskWorker();
startRenderFallback();
httpServer.listen(env.PORT, () => console.log(`Drex API listening on ${env.PORT}`));
